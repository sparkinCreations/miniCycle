// ── helpers ────────────────────────────────────────────────────────────────
function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}
function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}
function copyFileEnsured(src, dest) {
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
}
function dirSize(p) {
  let total = 0;
  for (const entry of fs.readdirSync(p, { withFileTypes: true })) {
    const full = path.join(p, entry.name);
    if (entry.isDirectory()) total += dirSize(full);
    else total += fs.statSync(full).size;
  }
  return total;
}
function human(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
function readVersion() {
  const src = fs.readFileSync(path.join(WEB_ROOT, 'version.js'), 'utf8');
  const m = src.match(/APP_VERSION\s*=\s*['"]([^'"]+)['"]/);
  if (!m) throw new Error('Could not parse APP_VERSION from version.js');
  return m[1];
}

// Replace lite-version fallback redirects with a no-op (lite/ is not bundled).
function neutralizeLiteRedirects(js) {
  return js.replace(
    /location\.replace\([^;]*lite\/miniCycle-lite\.html[^;]*\);/g,
    "console.warn('[miniCycle-ext] lite fallback suppressed (full extension build)');"
  );
}

// ── inline-script classification ────────────────────────────────────────────
// Each rule is tested against an inline block's JS body. First match wins.
// action: 'drop'  -> remove the block (leave an HTML comment marker)
//         'split' -> keep only the body before `marker`, externalize that part
//         (default, no rule match) -> externalize the whole block
const RULES = [
  { test: /__miniCycle_bootFails/,                         action: 'drop',  why: 'boot-failure failsafe (PWA cache clear)' },
  { test: /document\.write/,                               action: 'drop',  why: 'version-change cache clear (PWA, document.write reload)' },
  { test: /Late fallback: only redirect if feature gate/, action: 'drop',  why: 'late lite-version fallback redirect' },
  { test: /Enhanced Service Worker Registration/,          action: 'split', why: 'feature gate kept; SW registration dropped',
    marker: '// ✅ Enhanced Service Worker Registration' },
];

function classify(body) {
  for (const rule of RULES) if (rule.test.test(body)) return rule;
  return { action: 'externalize' };
}

// ── 1. transform miniCycle.html -> index.html ───────────────────────────────
function transformHtml() {
  let html = fs.readFileSync(path.join(WEB_ROOT, 'miniCycle.html'), 'utf8');

  // PWA manifest is irrelevant in an extension (and the name collides with the
  // extension manifest). Drop the link.
  html = html.replace(
    /<link\s+rel="manifest"[^>]*>/i,
    '<!-- [chrome-ext build] removed PWA manifest link -->'
  );

  // Info/nav links to pages NOT bundled in the extension (pages/, tests/) would
  // 404 from a chrome-extension:// origin. They open in a new tab, so point them
  // at the canonical live site instead. NOTE: legal/ is deliberately NOT rewritten
  // here — those pages ARE bundled (see copyLegal) so they open inside the
  // extension; rewriting them to the live site would strand an extension user on
  // minicycle.app (its "Back to miniCycle" returns to the WEB app, not the ext).
  html = html.replace(
    /href="((?:pages|tests)\/[^"]*)"/g,
    `href="${LIVE_SITE}/$1"`
  );

  // Match ONLY inline blocks: `<script>` with no attributes. `<script src=...>`
  // and `<script type="module" ...>` are left untouched (version.js + the main
  // module entry stay as external refs).
  let externalIndex = 0;
  const dropped = [];
  const externalized = [];

  html = html.replace(/<script>([\s\S]*?)<\/script>/g, (_match, body) => {
    const rule = classify(body);

    if (rule.action === 'drop') {
      dropped.push(rule.why);
      return `<!-- [chrome-ext build] removed inline script: ${rule.why} -->`;
    }

    let js = body;
    if (rule.action === 'split') {
      const idx = js.indexOf(rule.marker);
      if (idx === -1) throw new Error(`Split marker not found: ${rule.marker}`);
      js = js.slice(0, idx);
      dropped.push('service-worker registration (tail of feature-gate block)');
    }

    js = neutralizeLiteRedirects(js);

    externalIndex += 1;
    const name = `${String(externalIndex).padStart(2, '0')}.js`;
    fs.writeFileSync(path.join(EXT_BOOT_DIR, name), js.trim() + '\n', 'utf8');
    externalized.push(name);
    return `<script src="ext-boot/${name}"></script>`;
  });

  // Inject the extension-only override stylesheet. After script processing the
  // only remaining </head> is the real one (the other lived in the dropped
  // document.write block), so a first-match replace is safe.
  fs.writeFileSync(path.join(OUT, 'ext-overrides.css'), EXT_OVERRIDES_CSS, 'utf8');
  html = html.replace(
    '</head>',
    '  <link rel="stylesheet" href="ext-overrides.css">\n</head>'
  );

  // Inject the "Open in full tab" escape hatch (side-panel → wide layout). It is
  // an external 'self' script (MV3-CSP safe), placed last so the DOM exists.
  fs.writeFileSync(path.join(EXT_BOOT_DIR, 'open-fulltab.js'), EXT_FULLTAB_JS, 'utf8');
  html = html.replace(
    '</body>',
    '  <script src="ext-boot/open-fulltab.js"></script>\n</body>'
  );

  fs.writeFileSync(path.join(OUT, 'index.html'), html, 'utf8');

  // Safety assertion: no inline <script> may survive (MV3 would block them).
  if (/<script>[\s\S]*?<\/script>/.test(html)) {
    throw new Error('An inline <script> block survived the transform — MV3 will block it.');
  }

  log(`index.html: externalized ${externalized.length} inline blocks -> ext-boot/, dropped ${dropped.length}`);
  dropped.forEach((d) => log(`   dropped: ${d}`));
  return { externalized };
}

// ── 2. copy app code verbatim ───────────────────────────────────────────────
function copyAppCode() {
  copyFileEnsured(path.join(WEB_ROOT, 'version.js'), path.join(OUT, 'version.js'));
  copyFileEnsured(path.join(WEB_ROOT, 'miniCycle-main.js'), path.join(OUT, 'miniCycle-main.js'));
  fs.cpSync(path.join(WEB_ROOT, 'modules'), path.join(OUT, 'modules'), { recursive: true });
  fs.cpSync(path.join(WEB_ROOT, 'styles'), path.join(OUT, 'styles'), { recursive: true });
  log(`copied version.js, miniCycle-main.js, modules/, styles/`);
}

// ── 3. prune + copy referenced assets ───────────────────────────────────────
function copyAssets() {
  // Always copy the (tiny) fonts dir — fonts.css uses relative url() refs.
  const fontsSrc = path.join(WEB_ROOT, 'assets', 'fonts');
  if (fs.existsSync(fontsSrc)) {
    fs.cpSync(fontsSrc, path.join(OUT, 'assets', 'fonts'), { recursive: true });
  }

  // Scan output HTML/CSS/JS for `assets/...` references (any leading ../ stripped
  // by anchoring the match at `assets/`). data: URIs contain no `assets/`.
  const scanFiles = [path.join(OUT, 'index.html')];
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (/\.(css|js)$/.test(e.name)) scanFiles.push(full);
    }
  };
  walk(path.join(OUT, 'styles'));
  walk(path.join(OUT, 'modules'));
  walk(EXT_BOOT_DIR);

  const refs = new Set();
  const re = /assets\/[A-Za-z0-9_./-]+\.[A-Za-z0-9]+/g;
  for (const f of scanFiles) {
    const txt = fs.readFileSync(f, 'utf8');
    let m;
    while ((m = re.exec(txt)) !== null) refs.add(m[0]);
  }

  let copied = 0;
  let missing = 0;
  for (const rel of refs) {
    const src = path.join(WEB_ROOT, rel);
    if (fs.existsSync(src) && fs.statSync(src).isFile()) {
      copyFileEnsured(src, path.join(OUT, rel));
      copied += 1;
    } else {
      missing += 1;
      log(`   WARN referenced asset not found: ${rel}`);
    }
  }
  log(`assets: copied fonts/ + ${copied} referenced files (${missing} missing refs ignored)`);
}

// ── 3b. copy runtime-fetched sample routines ────────────────────────────────
// The app fetch()es these at runtime (onboarding first-run + "load sample"):
//   /examples/sample-routines/manifest.json  (+ the .mcyc files it lists)
//   examples/initial-run/Your_First_Routine.mcyc
// The leading-slash path resolves to the extension root, so they live at
// chrome/full/examples/. Other examples/ subdirs (pwa-reference/, routines/)
// are dev scratch — pwa-reference even ships its own sw.js — so exclude them.
// Defensive check below warns if a new examples/<dir> reference appears.
const EXAMPLE_DIRS = ['sample-routines', 'initial-run'];

function copyExamples() {
  for (const dir of EXAMPLE_DIRS) {
    const src = path.join(WEB_ROOT, 'examples', dir);
    if (fs.existsSync(src)) {
      fs.cpSync(src, path.join(OUT, 'examples', dir), { recursive: true });
    } else {
      log(`   WARN example dir not found: examples/${dir}`);
    }
  }

  // Surface any examples/<dir> referenced by modules that we did NOT bundle.
  const referenced = new Set();
  const re = /examples\/([A-Za-z0-9_-]+)\//g;
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) scan(full);
      else if (/\.js$/.test(e.name)) {
        let m;
        const txt = fs.readFileSync(full, 'utf8');
        while ((m = re.exec(txt)) !== null) referenced.add(m[1]);
      }
    }
  };
  scan(path.join(OUT, 'modules'));
  for (const d of referenced) {
    if (!EXAMPLE_DIRS.includes(d)) {
      log(`   WARN modules fetch examples/${d}/ but it is not in EXAMPLE_DIRS — add it`);
    }
  }
  log(`examples: copied ${EXAMPLE_DIRS.join(', ')}`);
}

// ── 3c. bundle legal pages (privacy / terms / security / accessibility …) ────
// The app's menu links to legal/*.html with target="_blank". If we left them
// rewritten to the live site (like pages/), an extension user who opened the
// Privacy Policy would land on minicycle.app and its "Back to miniCycle" button
// (and legal-footer.js, which is referrer-driven) would return them to the WEB
// app — bouncing them out of the extension. So bundle legal/ and keep its links
// internal. Two rewrites per bundled page:
//   ../miniCycle.html  -> ../index.html   (the extension's entry is index.html)
//   ../pages/<x>       -> live site       (pages/ is not bundled)
// Sibling legal links (privacy<->terms) and absolute https links stay as-is.
function copyLegal() {
  const src = path.join(WEB_ROOT, 'legal');
  if (!fs.existsSync(src)) { log('   WARN legal/ not found — skipping'); return; }
  const dest = path.join(OUT, 'legal');
  fs.cpSync(src, dest, { recursive: true });

  let patched = 0;
  for (const e of fs.readdirSync(dest, { withFileTypes: true })) {
    if (!e.isFile() || !e.name.endsWith('.html')) continue;
    const p = path.join(dest, e.name);
    const before = fs.readFileSync(p, 'utf8');
    const after = before
      .replace(/href="\.\.\/miniCycle\.html"/g, 'href="../index.html"')
      .replace(/href="\.\.\/pages\/([^"]*)"/g, `href="${LIVE_SITE}/pages/$1"`);
    if (after !== before) { fs.writeFileSync(p, after, 'utf8'); patched += 1; }
  }
  log(`legal: bundled legal/ (${patched} page(s) re-linked to the extension)`);
}

// ── 3d. bundle the unlockable Task Order mini-game ───────────────────────────
// gamesManager sends the user to games/miniCycle-taskOrder.html when they unlock
// the Task Order game at 100 global cycles. Bundle that ONE game + its two
// scripts (both external <script src> refs — MV3-CSP safe). Its "Back to
// miniCycle" button navigates to ../miniCycle.html, which is index.html in this
// build, so rewrite it. The other games/ files (taskGame, taskScramble) are dead
// experiments carrying inline <script>; they are never linked from the app and
// are deliberately left out so no inline-script HTML ships in the MV3 package.
// The game's favicon + variables.css are already covered (assets scan + styles copy).
const GAME_FILES = [
  'miniCycle-taskOrder.html',
  'miniCycle-taskOrder.js',
  'miniCycle-taskOrder-init.js',
];

function copyGames() {
  const srcDir = path.join(WEB_ROOT, 'games');
  const destDir = path.join(OUT, 'games');
  let copied = 0;
  for (const name of GAME_FILES) {
    const src = path.join(srcDir, name);
    if (!fs.existsSync(src)) { log(`   WARN game file not found: games/${name}`); continue; }
    if (name.endsWith('.js')) {
      // Back-to-app navigation: web entry is miniCycle.html; here it is index.html.
      const before = fs.readFileSync(src, 'utf8');
      const after = before.replace(/(["'])\.\.\/miniCycle\.html\1/g, '$1../index.html$1');
      ensureDir(destDir);
      fs.writeFileSync(path.join(destDir, name), after, 'utf8');
    } else {
      copyFileEnsured(src, path.join(destDir, name));
    }
    copied += 1;
  }
  log(`games: bundled ${copied} file(s) (Task Order mini-game)`);
}

// ── 3e. avoid the Chrome Web Store "more than one manifest.json" rejection ───
// The bundled sample-routines listing file is named manifest.json (app data that
// lists the .mcyc samples, fetched at runtime). The Web Store rejects any package
// containing more than one manifest.json, so in the EXTENSION we rename it to
// index.json and patch its single fetch in the copied routineManager.js. The web
// app keeps manifest.json — this collision is an extension-packaging concern only.
function dedupeSampleManifest() {
  const from = path.join(OUT, 'examples', 'sample-routines', 'manifest.json');
  const to = path.join(OUT, 'examples', 'sample-routines', 'index.json');
  if (!fs.existsSync(from)) { log('   note: no sample-routines/manifest.json — skipping dedupe'); return; }
  fs.renameSync(from, to);

  const mod = path.join(OUT, 'modules', 'routine', 'routineManager.js');
  const ref = '/examples/sample-routines/manifest.json';
  if (fs.existsSync(mod)) {
    const before = fs.readFileSync(mod, 'utf8');
    const after = before.split(ref).join('/examples/sample-routines/index.json');
    if (after !== before) fs.writeFileSync(mod, after, 'utf8');
    else log(`   WARN expected fetch '${ref}' not found in routineManager.js — verify the rename`);
  }
  log('sample routines: renamed manifest.json -> index.json (single manifest in package)');
}

// Hard guard: a Web Store package must contain exactly ONE manifest.json (the
// extension manifest at the root). Throw if a stray one slips back in.
function assertSingleManifest() {
  const count = (function walk(dir) {
    let n = 0;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) n += walk(full);
      else if (e.name === 'manifest.json') n += 1;
    }
    return n;
  })(OUT);
  if (count !== 1) {
    throw new Error(`Expected exactly 1 manifest.json in the package, found ${count} — the Web Store will reject this upload.`);
  }
}

