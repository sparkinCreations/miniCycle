#!/usr/bin/env node
/**
 * build-capacitor-www.cjs — Port the full miniCycle web app (web/) into the web
 * payload of a Capacitor app: mobile/android/www/ or mobile/ios/www/.
 *
 * This is the SHARED ENGINE behind the per-platform entry points
 * (build-android-www.cjs / build-ios-www.cjs — thin shims that call run()).
 * The transform is identical for both platforms; only the output directory and
 * the injected per-platform overrides stylesheet differ (see PLATFORMS below).
 *
 * Form factor: a Capacitor WebView app. The bundled www/ is copied into the
 * native project (android: android/app/src/main/assets/public/, ios:
 * ios/App/App/public/) by `npx cap sync` and served from a local origin
 * (android: http://localhost, ios: capacitor://localhost) inside the app's
 * WebView. There is no server and no store-packaging CSP — the differences from
 * the web app are therefore SMALLER than the Chrome extension's:
 *
 *   - The WebView enforces NO strict CSP (miniCycle.html has no meta CSP), so
 *     inline <script> blocks are LEFT INLINE — unlike the MV3 extension build,
 *     this script does NOT externalize them to ext-boot/NN.js.
 *   - The PWA service worker / cache-versioning machinery is irrelevant (assets
 *     ship bundled locally) and would risk pinning stale code, so the same
 *     PWA-only inline blocks the Chrome build drops are dropped here too.
 *
 * So the transform here is essentially the Chrome transform MINUS externalization:
 *   1. Rewrite miniCycle.html -> index.html:
 *        - DROP the PWA-only inline blocks (boot-failure failsafe, document.write
 *          version reload, the ~558-line service-worker registration; the feature
 *          gate before it is kept).
 *        - NEUTRALIZE the lite-version fallback redirects (lite/ is not bundled).
 *        - DROP the <link rel="manifest"> (PWA manifest is unused in the WebView).
 *        - Rewrite pages/ + tests/ links to the live site (not bundled).
 *        - Inject the per-platform overrides css (hides the automated-test tab;
 *          tests/ is not bundled and its iframe would 404).
 *   2. Copy the app verbatim: version.js, miniCycle-main.js, modules/, styles/.
 *   3. Prune assets: copy only referenced files (+ fonts/), like the Chrome build.
 *   4. Bundle runtime-fetched examples/ and the legal/ pages.
 *
 * Inline-block classification is content-based (stable substrings), NOT line
 * numbers, so it survives edits to miniCycle.html — same RULES contract as
 * build-chrome-full.cjs. If the HTML's inline scripts are restructured, revisit
 * the RULES table below (and the sibling Chrome script).
 *
 * The native manifest, app id, icons, splash, and Gradle/Xcode config live in
 * the committed Capacitor projects under mobile/android/ and mobile/ios/ — they
 * are NOT generated here. This script only produces the web payload. Run on
 * every release:
 *   npm run build:android   (then: cd mobile/android && npx cap sync android)
 *   npm run build:ios       (then: cd mobile/ios     && npx cap sync ios)
 *
 * No third-party deps — Node stdlib only (fs/path). Idempotent: rmrf + regen.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const WEB_ROOT = path.resolve(__dirname, '..');                       // .../web
const REPO_ROOT = path.resolve(WEB_ROOT, '..');                       // repo root
const LIVE_SITE = 'https://minicycle.app';                            // canonical host for unbundled info pages

// Platform-only UI overrides (injected into <head>). The in-app automated test
// runner loads tests/module-test-suite.html in an iframe, but tests/ is dev-only
// and intentionally not bundled, so it 404s inside the WebView. Hide its tab so
// it can't be triggered. (Run the suite locally in web/ — the app ships
// byte-identical modules.)
const HIDE_TEST_TAB_CSS = `.testing-tab[data-tab="automated-tests"],
#automated-tests-tab { display: none !important; }
`;

const PLATFORMS = {
  android: {
    outDir: path.join(REPO_ROOT, 'mobile', 'android', 'www'),
    overridesFile: 'android-overrides.css',
    overridesCss:
      '/* Generated by build-android-www.cjs — Android-only UI overrides. Do not edit by hand. */\n' +
      HIDE_TEST_TAB_CSS,
    next: 'cd mobile/android && npx cap sync android',
  },
  ios: {
    outDir: path.join(REPO_ROOT, 'mobile', 'ios', 'www'),
    overridesFile: 'ios-overrides.css',
    overridesCss:
      '/* Generated by build-ios-www.cjs — iOS-only UI overrides. Do not edit by hand. */\n' +
      HIDE_TEST_TAB_CSS,
    next: 'cd mobile/ios && npx cap sync ios',
  },
};

// Set by run(); read by every step below.
let PLATFORM = null;   // 'android' | 'ios'
let CFG = null;        // PLATFORMS[PLATFORM]
let OUT = null;        // CFG.outDir

function log(msg) {
  console.log(`[build-${PLATFORM}-www] ${msg}`);
}

function rmrf(p) {
  // maxRetries/retryDelay make rmSync resilient to ENOTEMPTY/EBUSY races on macOS
  // (e.g. a stray Finder name-collision dir like "assets 2/" left in www/), which
  // otherwise throws mid-removal and leaves a half-cleared, stale payload.
  fs.rmSync(p, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}
function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}
function copyFileEnsured(src, dest) {
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
}
function dirSize(p) {
  let total = 0;
  for (const entry of fs.readdirSync(p, { withFileTypes: true })) {
    const full = path.join(p, entry.name);
    if (entry.isDirectory()) total += dirSize(full);
    else total += fs.statSync(full).size;
  }
  return total;
}
function human(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}
function readVersion() {
  const src = fs.readFileSync(path.join(WEB_ROOT, 'version.js'), 'utf8');
  const m = src.match(/APP_VERSION\s*=\s*['"]([^'"]+)['"]/);
  if (!m) throw new Error('Could not parse APP_VERSION from version.js');
  return m[1];
}

// Replace lite-version fallback redirects with a no-op (lite/ is not bundled).
function neutralizeLiteRedirects(js) {
  return js.replace(
    /location\.replace\([^;]*lite\/miniCycle-lite\.html[^;]*\);/g,
    `console.warn('[miniCycle-${PLATFORM}] lite fallback suppressed (Capacitor build)');`
  );
}

// ── inline-script classification ────────────────────────────────────────────
// Each rule is tested against an inline block's JS body. First match wins.
// action: 'drop'  -> remove the block (leave an HTML comment marker)
//         'split' -> keep only the body before `marker` (inline); drop the rest
//         (default, no rule match) -> KEEP the block inline, unchanged
//
// Unlike the Chrome (MV3) build, the default action is "keep inline" — the
// Capacitor WebView enforces no strict CSP, so inline scripts are allowed.
const RULES = [
  { test: /__miniCycle_bootFails/,                         action: 'drop',  why: 'boot-failure failsafe (PWA cache clear)' },
  { test: /document\.write/,                               action: 'drop',  why: 'version-change cache clear (PWA, document.write reload)' },
  { test: /Late fallback: only redirect if feature gate/, action: 'drop',  why: 'late lite-version fallback redirect' },
  { test: /Enhanced Service Worker Registration/,          action: 'split', why: 'feature gate kept; SW registration dropped',
    marker: '// ✅ Enhanced Service Worker Registration' },
];

function classify(body) {
  for (const rule of RULES) if (rule.test.test(body)) return rule;
  return { action: 'keep' };
}

// ── 1. transform miniCycle.html -> index.html ───────────────────────────────
function transformHtml() {
  let html = fs.readFileSync(path.join(WEB_ROOT, 'miniCycle.html'), 'utf8');

  // PWA manifest is unused inside the Capacitor WebView. Drop the link.
  html = html.replace(
    /<link\s+rel="manifest"[^>]*>/i,
    `<!-- [${PLATFORM} build] removed PWA manifest link -->`
  );

  // Info/nav links to pages NOT bundled (pages/, tests/) would 404 from the
  // local WebView origin. They open in a new tab, so point them at the live
  // site instead. NOTE: legal/ is deliberately NOT rewritten here — those pages
  // ARE bundled (see copyLegal) so they open inside the app.
  html = html.replace(
    /href="((?:pages|tests)\/[^"]*)"/g,
    `href="${LIVE_SITE}/$1"`
  );

  // Process ONLY inline blocks: `<script>` with no attributes. `<script src=...>`
  // and `<script type="module" ...>` are left untouched (version.js + the main
  // module entry stay as external refs). The default action keeps the block
  // inline verbatim — only PWA-specific blocks are dropped/split.
  const dropped = [];
  let kept = 0;

  html = html.replace(/<script>([\s\S]*?)<\/script>/g, (match, body) => {
    const rule = classify(body);

    if (rule.action === 'drop') {
      dropped.push(rule.why);
      return `<!-- [${PLATFORM} build] removed inline script: ${rule.why} -->`;
    }

    if (rule.action === 'split') {
      const idx = body.indexOf(rule.marker);
      if (idx === -1) throw new Error(`Split marker not found: ${rule.marker}`);
      dropped.push('service-worker registration (tail of feature-gate block)');
      const head = neutralizeLiteRedirects(body.slice(0, idx));
      kept += 1;
      return `<script>${head}</script>`;
    }

    // keep: leave inline, but still neutralize any lite-redirect inside it.
    kept += 1;
    const js = neutralizeLiteRedirects(body);
    return js === body ? match : `<script>${js}</script>`;
  });

  // Inject the platform-only override stylesheet before the (single remaining)
  // </head>. The other </head> lived in the dropped document.write block.
  fs.writeFileSync(path.join(OUT, CFG.overridesFile), CFG.overridesCss, 'utf8');
  html = html.replace(
    '</head>',
    `  <link rel="stylesheet" href="${CFG.overridesFile}">\n</head>`
  );

  fs.writeFileSync(path.join(OUT, 'index.html'), html, 'utf8');
  log(`index.html: kept ${kept} inline blocks, dropped ${dropped.length}`);
  dropped.forEach((d) => log(`   dropped: ${d}`));
}

// ── 2. copy app code verbatim ───────────────────────────────────────────────
function copyAppCode() {
  copyFileEnsured(path.join(WEB_ROOT, 'version.js'), path.join(OUT, 'version.js'));
  copyFileEnsured(path.join(WEB_ROOT, 'miniCycle-main.js'), path.join(OUT, 'miniCycle-main.js'));
  fs.cpSync(path.join(WEB_ROOT, 'modules'), path.join(OUT, 'modules'), { recursive: true });
  fs.cpSync(path.join(WEB_ROOT, 'styles'), path.join(OUT, 'styles'), { recursive: true });
  log('copied version.js, miniCycle-main.js, modules/, styles/');
}

// ── 3. prune + copy referenced assets ───────────────────────────────────────
function copyAssets() {
  // Always copy the (tiny) fonts dir — fonts.css uses relative url() refs.
  const fontsSrc = path.join(WEB_ROOT, 'assets', 'fonts');
  if (fs.existsSync(fontsSrc)) {
    fs.cpSync(fontsSrc, path.join(OUT, 'assets', 'fonts'), { recursive: true });
  }

  // Scan output HTML/CSS/JS for `assets/...` references (any leading ../ stripped
  // by anchoring the match at `assets/`). data: URIs contain no `assets/`.
  const scanFiles = [path.join(OUT, 'index.html')];
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (/\.(css|js)$/.test(e.name)) scanFiles.push(full);
    }
  };
  walk(path.join(OUT, 'styles'));
  walk(path.join(OUT, 'modules'));

  const refs = new Set();
  const re = /assets\/[A-Za-z0-9_./-]+\.[A-Za-z0-9]+/g;
  for (const f of scanFiles) {
    const txt = fs.readFileSync(f, 'utf8');
    let m;
    while ((m = re.exec(txt)) !== null) refs.add(m[0]);
  }

  let copied = 0;
  let missing = 0;
  for (const rel of refs) {
    const src = path.join(WEB_ROOT, rel);
    if (fs.existsSync(src) && fs.statSync(src).isFile()) {
      copyFileEnsured(src, path.join(OUT, rel));
      copied += 1;
    } else {
      missing += 1;
      log(`   WARN referenced asset not found: ${rel}`);
    }
  }
  log(`assets: copied fonts/ + ${copied} referenced files (${missing} missing refs ignored)`);
}

// ── 3b. copy runtime-fetched sample routines ────────────────────────────────
// The app fetch()es these at runtime (onboarding first-run + "load sample").
// The leading-slash paths resolve to the WebView root, so they live at www/.
// Other examples/ subdirs (pwa-reference/, routines/) are dev scratch — exclude.
const EXAMPLE_DIRS = ['sample-routines', 'initial-run'];

function copyExamples() {
  for (const dir of EXAMPLE_DIRS) {
    const src = path.join(WEB_ROOT, 'examples', dir);
    if (fs.existsSync(src)) {
      fs.cpSync(src, path.join(OUT, 'examples', dir), { recursive: true });
    } else {
      log(`   WARN example dir not found: examples/${dir}`);
    }
  }

  // Surface any examples/<dir> referenced by modules that we did NOT bundle.
  const referenced = new Set();
  const re = /examples\/([A-Za-z0-9_-]+)\//g;
  const scan = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) scan(full);
      else if (/\.js$/.test(e.name)) {
        let m;
        const txt = fs.readFileSync(full, 'utf8');
        while ((m = re.exec(txt)) !== null) referenced.add(m[1]);
      }
    }
  };
  scan(path.join(OUT, 'modules'));
  for (const d of referenced) {
    if (!EXAMPLE_DIRS.includes(d)) {
      log(`   WARN modules fetch examples/${d}/ but it is not in EXAMPLE_DIRS — add it`);
    }
  }
  log(`examples: copied ${EXAMPLE_DIRS.join(', ')}`);
}

// ── 3c. bundle legal pages (privacy / terms / security / accessibility …) ────
// The app's menu links to legal/*.html with target="_blank". Bundle them and
// keep links internal so a user who opens the Privacy Policy stays in the app:
//   ../miniCycle.html  -> ../index.html   (the app's entry is index.html)
//   ../pages/<x>       -> live site       (pages/ is not bundled)
// Sibling legal links (privacy<->terms) and absolute https links stay as-is.
function copyLegal() {
  const src = path.join(WEB_ROOT, 'legal');
  if (!fs.existsSync(src)) { log('   WARN legal/ not found — skipping'); return; }
  const dest = path.join(OUT, 'legal');
  fs.cpSync(src, dest, { recursive: true });

  let patched = 0;
  for (const e of fs.readdirSync(dest, { withFileTypes: true })) {
    if (!e.isFile() || !e.name.endsWith('.html')) continue;
    const p = path.join(dest, e.name);
    const before = fs.readFileSync(p, 'utf8');
    const after = before
      .replace(/href="\.\.\/miniCycle\.html"/g, 'href="../index.html"')
      .replace(/href="\.\.\/pages\/([^"]*)"/g, `href="${LIVE_SITE}/pages/$1"`);
    if (after !== before) { fs.writeFileSync(p, after, 'utf8'); patched += 1; }
  }
  log(`legal: bundled legal/ (${patched} page(s) re-linked to the app)`);
}

// ── 4. prune OS junk ────────────────────────────────────────────────────────
function pruneJunk() {
  let removed = 0;
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name === '.DS_Store' || e.name === 'Thumbs.db') {
        fs.rmSync(full);
        removed += 1;
      }
    }
  };
  walk(OUT);
  if (removed) log(`pruned ${removed} OS junk file(s) (.DS_Store / Thumbs.db)`);
}

// ── run ──────────────────────────────────────────────────────────────────────
function run(platform) {
  if (!PLATFORMS[platform]) {
    throw new Error(`Unknown platform "${platform}" — expected one of: ${Object.keys(PLATFORMS).join(', ')}`);
  }
  PLATFORM = platform;
  CFG = PLATFORMS[platform];
  OUT = CFG.outDir;

  log(`source: ${WEB_ROOT}`);
  log(`output: ${OUT}`);
  rmrf(OUT);
  ensureDir(OUT);

  const version = readVersion();
  transformHtml();
  copyAppCode();
  copyAssets();
  copyExamples();
  copyLegal();
  pruneJunk();

  log(`done — v${version}, ${human(dirSize(OUT))} total`);
  log(`next: ${CFG.next}`);
}

module.exports = { run };

// Direct invocation: `node build-capacitor-www.cjs <android|ios>`
if (require.main === module) {
  run(process.argv[2] || 'android');
}
